'use client';

import { useCallback, useRef, useState } from 'react';
import { JUDGE_ENDPOINT, normalizeDoi, summarize, doiUrl, type JudgeResponse, type Verdict } from '@/lib/judge';

const EXAMPLES = [
  { doi: '10.1016/S0140-6736(97)11096-0', label: 'Wakefield 1998 (retracted)' },
  { doi: '10.1038/nature14581', label: 'Nature 2015 (not retracted)' },
  { doi: '10.9999/not-in-snapshot', label: 'Unknown DOI (abstains)' },
];

const VERDICT_STYLE: Record<Verdict['kind'], { bg: string; label: string }> = {
  retracted: { bg: 'var(--pink)', label: 'Retracted' },
  not_retracted: { bg: 'var(--mint)', label: 'Not retracted' },
  no_status_rows: { bg: 'var(--yellow)', label: 'No status rows' },
  abstained: { bg: 'var(--blue)', label: 'Abstained' },
};

type State =
  | { phase: 'idle' }
  | { phase: 'loading'; doi: string }
  | { phase: 'done'; doi: string; verdict: Verdict; data: JudgeResponse; ms: number }
  | { phase: 'error'; doi: string; message: string };

export default function JudgeLookup() {
  const [value, setValue] = useState('');
  const [state, setState] = useState<State>({ phase: 'idle' });
  const abortRef = useRef<AbortController | null>(null);

  const run = useCallback(async (raw: string) => {
    const doi = normalizeDoi(raw);
    if (!doi) {
      setState({ phase: 'error', doi: raw.trim(), message: 'That does not look like a DOI. Expected something like 10.1056/NEJMoa2034577.' });
      return;
    }
    abortRef.current?.abort();
    const controller = new AbortController();
    abortRef.current = controller;
    setState({ phase: 'loading', doi });
    const started = performance.now();
    const timer = setTimeout(() => controller.abort(), 20000);
    try {
      const res = await fetch(`${JUDGE_ENDPOINT}?doi=${encodeURIComponent(doi)}`, {
        headers: { Accept: 'application/json' },
        signal: controller.signal,
      });
      const ms = Math.round(performance.now() - started);
      if (!res.ok) {
        setState({ phase: 'error', doi, message: `The endpoint answered HTTP ${res.status}. It is a free read-only route; a 429 means you are being rate limited, so wait a minute.` });
        return;
      }
      const data = (await res.json()) as JudgeResponse;
      setState({ phase: 'done', doi, verdict: summarize(data), data, ms });
    } catch (error) {
      const aborted = error instanceof DOMException && error.name === 'AbortError';
      setState({
        phase: 'error',
        doi,
        message: aborted
          ? 'The request took longer than 20 seconds. Slow days happen; retry once before assuming the service is down.'
          : 'The browser could not reach pay.ashesborn.cloud. Check connectivity or an extension blocking cross-origin requests.',
      });
    } finally {
      clearTimeout(timer);
    }
  }, []);

  return (
    <section className="brutal-card" style={{ marginBottom: 28 }}>
      <p className="brutal-kicker" style={{ margin: 0 }}>Free · no key · no account</p>
      <h2 className="brutal-title" style={{ fontSize: 26, margin: '6px 0 10px' }}>
        Check any DOI for retraction
      </h2>
      <p className="brutal-text" style={{ marginTop: 0 }}>
        One HTTP GET against the live snapshot. The response lists every source that covers the paper, its
        source tier (A = registry-grade, C = index-derived) and the retraction date when a source records one.
        Nothing is generated by a model, so the same DOI returns the same answer.
      </p>

      <form
        onSubmit={(event) => {
          event.preventDefault();
          void run(value);
        }}
        style={{ display: 'flex', gap: 10, flexWrap: 'wrap', marginTop: 14 }}
      >
        <label htmlFor="doi-input" style={{ position: 'absolute', left: -9999 }}>
          DOI
        </label>
        <input
          id="doi-input"
          value={value}
          onChange={(event) => setValue(event.target.value)}
          placeholder="10.1016/S0140-6736(97)11096-0"
          spellCheck={false}
          autoComplete="off"
          style={{
            flex: '1 1 340px',
            minWidth: 240,
            padding: '12px 14px',
            border: 'var(--brutal-border)',
            borderRadius: 4,
            fontFamily: 'var(--brutal-mono)',
            fontSize: 14,
            background: '#fff',
          }}
        />
        <button
          type="submit"
          className="brutal-btn brutal-btn--ink"
          disabled={state.phase === 'loading'}
          style={{ opacity: state.phase === 'loading' ? 0.6 : 1 }}
        >
          {state.phase === 'loading' ? 'Checking…' : 'Check status'}
        </button>
      </form>

      <div style={{ display: 'flex', gap: 8, flexWrap: 'wrap', marginTop: 12 }}>
        {EXAMPLES.map((example) => (
          <button
            key={example.doi}
            type="button"
            className="brutal-pill"
            onClick={() => {
              setValue(example.doi);
              void run(example.doi);
            }}
            style={{ cursor: 'pointer' }}
          >
            {example.label}
          </button>
        ))}
      </div>

      <div aria-live="polite" style={{ marginTop: 18 }}>
        {state.phase === 'loading' && (
          <p className="brutal-muted" style={{ fontFamily: 'var(--brutal-mono)', fontSize: 13 }}>
            GET {JUDGE_ENDPOINT}?doi={state.doi}
          </p>
        )}

        {state.phase === 'error' && (
          <div style={{ border: 'var(--brutal-border)', borderRadius: 4, padding: 14, background: '#fff' }}>
            <strong>Could not answer.</strong>
            <p style={{ margin: '6px 0 0' }}>{state.message}</p>
            <p className="brutal-muted" style={{ margin: '8px 0 0', fontFamily: 'var(--brutal-mono)', fontSize: 12 }}>
              doi: {state.doi || '(empty)'}
            </p>
          </div>
        )}

        {state.phase === 'done' && <Result state={state} />}
      </div>
    </section>
  );
}

function Result({ state }: { state: Extract<State, { phase: 'done' }> }) {
  const { verdict, data, doi, ms } = state;
  const style = VERDICT_STYLE[verdict.kind];
  const title = data.paper?.title;

  return (
    <div style={{ border: 'var(--brutal-border)', borderRadius: 4, background: '#fff', overflow: 'hidden' }}>
      <div style={{ background: style.bg, padding: '12px 14px', borderBottom: 'var(--brutal-border)' }}>
        <div style={{ display: 'flex', justifyContent: 'space-between', gap: 12, flexWrap: 'wrap', alignItems: 'baseline' }}>
          <strong style={{ fontSize: 18 }}>{style.label}</strong>
          <span style={{ fontFamily: 'var(--brutal-mono)', fontSize: 12 }}>
            {ms} ms · {data.statuses.length} source{data.statuses.length === 1 ? '' : 's'}
            {verdict.tiers ? ` · tier ${verdict.tiers}` : ''}
          </span>
        </div>
      </div>

      <div style={{ padding: 14 }}>
        <p style={{ margin: '0 0 10px' }}>{verdict.reading}</p>

        {title && (
          <p style={{ margin: '0 0 10px', fontStyle: 'italic' }}>
            {title} {data.paper?.year ? `(${data.paper.year})` : ''}{' '}
            <a className="brutal-link" href={doiUrl(doi)} target="_blank" rel="noreferrer noopener">
              doi.org/{doi}
            </a>
          </p>
        )}

        {data.statuses.length > 0 && (
          <div style={{ overflowX: 'auto' }}>
            <table style={{ borderCollapse: 'collapse', width: '100%', fontSize: 13 }}>
              <thead>
                <tr>
                  {['Source', 'Tier', 'Says', 'Retraction date'].map((head) => (
                    <th
                      key={head}
                      style={{ textAlign: 'left', padding: '6px 8px', borderBottom: 'var(--brutal-border)' }}
                    >
                      {head}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {data.statuses.map((status) => (
                  <tr key={`${status.source}-${status.paper_id}`}>
                    <td style={{ padding: '6px 8px', borderBottom: '1px solid #e6e0d4', fontFamily: 'var(--brutal-mono)' }}>
                      {status.source}
                    </td>
                    <td style={{ padding: '6px 8px', borderBottom: '1px solid #e6e0d4' }}>{status.source_tier}</td>
                    <td style={{ padding: '6px 8px', borderBottom: '1px solid #e6e0d4' }}>
                      {status.is_retracted ? 'retracted' : 'not retracted'}
                    </td>
                    <td style={{ padding: '6px 8px', borderBottom: '1px solid #e6e0d4' }}>
                      {status.retraction_date ?? '—'}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}

        <details style={{ marginTop: 12 }}>
          <summary style={{ cursor: 'pointer', fontFamily: 'var(--brutal-mono)', fontSize: 13 }}>
            Raw response
          </summary>
          <pre
            style={{
              overflowX: 'auto',
              background: '#111',
              color: '#f7f3e8',
              padding: 12,
              borderRadius: 4,
              fontSize: 12,
              marginTop: 8,
            }}
          >
            {JSON.stringify(data, null, 2)}
          </pre>
        </details>
      </div>
    </div>
  );
}
